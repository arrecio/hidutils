class Item:
    TYPE_MAIN = 0x00
    TYPE_GLOBAL = 0x04
    TYPE_LOCAL = 0x08

    def __init__(self, prefix, data, itemDesc, extended=None):
        self.prefix = prefix
        self.iType = prefix & 0x0C
        self.tag = itemDesc[0]
        self.name = itemDesc[1]
        self.data = data
        self.extended = extended


