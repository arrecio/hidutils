# HidDevice class
# encapsulates a hid.Device class (wich uses hidapi to access the hardware).
#
# see:
# https://www.usb.org/sites/default/files/hid1_11.pdf
# https://www.usb.org/sites/default/files/hut1_7.pdf
#
# Must known:
# A HID is a device with a vendorId:productId unique pair
# A HID must have a HID report descriptor, that descriptor talks about the form of the USB data frame
# to read (Input reports) or write (Output, Feature reports)
# We can call "control" a source of data wich talks about the state of an axis or button (for example)
# An Input report can contain multiple "controls" data, every control in an input report shares
# how the data is stored and processed. For example a bit array with [0,1] for button states.
# In Input reports, each control (or source of data) has a name associated, Hid Usage Tables
# is the specification to translate usagePage/usage pair to human readable form.
# The control usage is orientative, is the one assigned by vendor. Joystick axes are usually assigned
# to X, Y, Z, Rx, Ry, Rz or Slider usages.
# H is for Human. A person uses the device for a specific purpose, usually to interact with the equipment
# by (mostly) pressing buttons or keys or by operating levers (axes) so buttons, keys and axes must be
# treated specially.
#
class HidDevice(hid.Device):
    def __init__(self, vendorId=None, productId=None, path=None, debug=False):
        if path:
            path = path.encode("utf-8")
        super().__init__(vendorId, productId, path=path)
        self.nonblocking = True
        self.__currentState = self.read(64)
        self.__lastState = [0] * len(self.__currentState)  # can be 0
        self.__hid_descriptor = HidReportDescriptor(self.get_report_descriptor())
        self.__inputReports = self.__hid_descriptor.inputs()
        self.__usageData = {}
        self.__inputUsage = []
        self.__byteWatch = []
        self.__usageWatch = []
        self.__updateTick = 0
        self.__readError = False
        self.__debug = debug
        self.__usageButtons = []
        self.__usageAxes = []
        # self.__numKeys = 0
        self.dump_hid_descriptor()
        for inputReport in self.__inputReports:
            for usageName in inputReport.usage:
                self.__inputUsage.append(usageName)
                if inputReport.flags & 0x02 == 0x02: # Variables
                    if inputReport.usagePage == 0x09: # Buttons
                        self.__usageButtons.append(usageName)
                    if inputReport.usagePage == 0x01 and usageName in ['X', 'Y', 'Z', 'Rx', 'Ry', 'Rz', 'Slider']: # Buttons
                        self.__usageAxes.append(usageName)
            # if inputReport.flags & 0x02 == 0 and inputReport.usageMinimun is not None: # Array
            #     if inputReport.usagePage == 0x07: # Keyboard
            #         self.__numKeys += (inputReport.usageMaximun - inputReport.usageMinimun)
            for b, uds in inputReport.byteMap.items():
                for ud in uds:
                    self.__usageData[ud[0]] = [0, inputReport, ud, 0]
        if debug:
            for i in self.__inputUsage:
                self.watch(i)

    # TODO split-join first?
    # def __getattr__(self, name: str):
    #     return self.__state[name]

    @property
    def numButtons(self):
        return len(self.__usageButtons)

    @property
    def numAxes(self):
        return len(self.__usageAxes)

    def inputUsages(self):
        return self.__inputUsage.copy()

    def watch(self, usage):
        if not usage in self.__usageData:
            return False
        if usage in self.__usageWatch:
            return True
        self.__usageWatch.append(usage)
        self.__rebuild_byte_watch()
        return True

    def unwatch(self, usage):
        if not usage in self.__usageData:
            return
        if not usage in self.__usageWatch:
            return
        self.__usageWatch.remove(usage)
        self.__rebuild_byte_watch()

    def watchAll(self):
        for i in self.__inputUsage:
            self.watch(i)

    # rebuild usage watch
    # the byte watching system avoids to examinate all the "state" for changes
    # this method marks for watch only the bytes where are allocated the data
    # or part of the data in the watching list
    def __rebuild_byte_watch(self):
        self.__byteWatch = []
        for inputReport in self.__inputReports:
            for b, uds in inputReport.byteMap.items():
                for ud in uds:
                    if ud[0] in self.__usageWatch:
                        for i in range(ud[1], ud[1] + ud[2]):
                            if not i in self.__byteWatch:
                                self.__byteWatch.append(i)

    # dups descriptor in a readable form
    def dump_hid_descriptor(self, raw=False, writer=sys.stdout.write):
        self.__hid_descriptor.dump(writer=writer)
        if raw:
            self.__hid_descriptor.dump_raw(writer=writer)
        if self.__debug:
            writer("Input data mapping:\n")
            for input in self.__inputReports:
                for i in input.byteMap:
                    for ud in input.byteMap[i]:
                        usage, index, size, mask, shift = ud
                        writer(
                            "  Usage: {}, Index: {}, Size: {}, Mask: {}, Shift: {}, Signed: {}\n".format(
                                usage, index, size, mask, shift, input.readSigned
                            )
                        )

    def get_state(self, usage):
        # if isConstant and _udateTick > 0: no leer
        if usage in self.__usageData:
            s = self.__usageData[usage]
            if self.__updateTick > s[3]:
                s[0] = self.__read_usage(s[1], s[2])
                s[3] = self.__updateTick
            return s[0]

    def __read_usage(self, input, usageDescriptor):
        usage, start, size, mask, shift = usageDescriptor
        c = int.from_bytes(
            self.__currentState[start : start + size], byteorder="little", signed=True
        )
        if mask:
            c = c & mask
        if shift:
            c = c >> shift
        if input.readSigned:
            m, s = 2**input.reportSize - 1, 2 ** (input.reportSize - 1)  # to byteMap?
            c = ((c & m) ^ s) - s
        return input.compute(c)

    # TODO: Constant dont need reread
    # Working with HidDevice requires calls to `update`.
    # The USB input frame is read here.
    # The goal is to enable consistent status queries,
    # avoiding multiple calls to `read`.
    def update(self, eventQueue=None):
        if not self.__inputReports:
            return
        reads = []
        try:
            # consume the input buffer every update
            read = self.read(64)
            while len(read) != 0:
                reads.append(read)
                read = self.read(64)
        except:
            self.__readError = True
            return
        self.__readError = False
        if len(reads) == 0:
            return
        for current in reads:
            # assert(len(current) >= self.__hid_descriptor.inputBitSize)
            self.__updateTick += 1
            self.__lastState = self.__currentState
            self.__currentState = current
            if len(self.__lastState) == 0: continue # first reading
            # Event watching
            if eventQueue is None and not self.__debug:
                return
            for i in self.__byteWatch:  # we dont look for what dont need
                if self.__lastState[i] != self.__currentState[i]:
                    for input in self.__inputReports:
                        if i in input.byteMap:
                            uds = input.byteMap[i]
                            for ud in uds:
                                usage, start, size, mask, shift = ud
                                if not usage in self.__usageWatch:
                                    continue
                                l = int.from_bytes(
                                    self.__lastState[start : start + size],
                                    byteorder="little",
                                )
                                c = int.from_bytes(
                                    self.__currentState[start : start + size],
                                    byteorder="little",
                                )
                                if mask:
                                    l = l & mask
                                    c = c & mask
                                if shift:
                                    l = l >> shift
                                    c = c >> shift
                                if l != c:
                                    c = input.compute(c)
                                    l = self.__usageData[usage][0] # read computed last from register
                                    self.__usageData[usage][0] = c
                                    self.__usageData[usage][3] = self.__updateTick
                                    if eventQueue is not None: eventQueue.append((self, usage, c, l))
                                    if self.__debug:
                                        print(
                                            "New value: ", usage, c
                                        )  # change to logging.debug?


# a Simple manager for HidDevices
class HidDeviceManager:
    def __init__(self, onPlug=None, onUnplug=None):
        assert onPlug is None or callable(onPlug)
        assert onUnplug is None or callable(onUnplug)
        self.__actions = {}
        self.__devices = {}
        self.__open_devices = {}
        self.__utils = HidUtils()
        self.__onPlug = onPlug
        self.__onUnplug = onUnplug
        self.__lastScan = 0
        self.__scanned = None
        self.__availableIndices = {}
        self.__aliases = {}

    def open(self, path, debug=False):
        if path in self.__open_devices:
            return self.__open_devices[path]

        device = None
        for device in self.__devices:
            if self.__devices[device]["path"] == path:
                device = self.__devices[device]
                break
        if not device:
            return False
        # adds the device to open devices
        hiddevice = self.__open_devices[path] = HidDevice(path=path, debug=debug)
        usage = "".join(device["usage"].split())
        if not usage in self.__availableIndices:
            self.__availableIndices[usage] = list(range(1, 10))
        indices = self.__availableIndices[usage]
        n = indices.pop(0)
        self.__aliases[path] = (usage+str(n), usage, n)
        if len(self.__availableIndices[usage]) == 1:
            indices.append(indices[0]+1)
        return hiddevice

    def __look_for_new_devices(self):
        ## seems very expensive operation (about 10ms), call every second or more?
        # go threading
        devices = self.__utils.get_devices()
        pluged = []
        unpluged = []
        for device in devices:
            if device in self.__devices:
                # already knows
                continue
            else:
                pluged.append(devices[device])
        for device in self.__devices:
            if device in devices:
                # still there
                continue
            else:
                unpluged.append(self.__devices[device])
        # dont worry about multithread, assignment is atomic op
        self.__scanned = (devices, pluged, unpluged)

    def setAction(self, event, actionName):
        self.__actions[event] = actionName

    def update(self, onEvent=None):
        t = int(time.time())
        if self.__lastScan != t:  # we scan every second
            thread = threading.Thread(target=self.__look_for_new_devices)
            thread.start()
            self.__lastScan = t
        # update device list
        if self.__scanned:
            self.__devices, pluged, unpluged = self.__scanned
            if self.__onPlug:
                for device in pluged:
                    self.__onPlug(self, device)
            for device in unpluged:
                if self.__onUnplug:
                    self.__onUnplug(self, device)
                path = device["path"]
                if path in self.__open_devices:
                    del self.__open_devices[path]
                    self.__availableIndices[self.__aliases[path][1]].insert(0, self.__aliases[path][2])
                    del self.__aliases[path]
            self.__scanned = None
        # t = time.time()
        queue = []
        for path, device in self.__open_devices.items():
            device.update(queue)
            for event in queue:
                if callable(onEvent):
                    onEvent(self.__aliases[path][0], event[1], event[2], event[3])
                    # onEvent(device, self.__aliases[path][0], event[1], event[2], event[3])
            queue.clear()
        # print(time.time()-t)

# A report for Hid Report Descriptor
# All data fields defined in a single item share an identical data format
class Report:
    def __init__(self, type):
        self.dataIndex = 0
        self.usagePage = 0
        self.reportId = None
        self.reportSize = 0  # bits
        self.reportCount = 0  # Number of controls (usually equal to len(self.usage))
        self.explicitUsage = False
        self.usageMinimun = self.usageMaximun = None
        self.physicalMinimun = self.physicalMaximun = None
        self.logicalMinimun = self.logicalMaximun = 0
        self.unit = None
        self.unitExponent = 0
        self.designatorIndex = self.designatorMaximun = self.designatorMinimun = None
        self.stringIndex = self.stringMaximun = self.stringMinimun = None
        self.signed = True
        self.__resolution = 1
        self.__m = self.__s = 0
        self.flags = 0
        self.done = False
        self.usage = []
        self.type = type

    def compute(self, rawVal):
        if self.signed: rawVal = ((rawVal & self.__m) ^ self.__s) - self.__s
        if self.flags & 0x02 == 0:  # Array? so we report value readed
            val = HidUtils.get_usage_name(self.usagePage, self.logicalMinimun + rawVal)
        else:  # Variable?
            val = rawVal * self.__resolution
        return val

    def build(self, arrayCount):
        isArray = self.flags & 0x02 == 0
        # adds usage minimun -> maximun if available
        if not self.usageMinimun is None and not self.usageMaximun is None:
            if isArray:
                for i in range(self.reportCount):
                    self.usage.append("Arr{}Val{}".format(arrayCount, i))
            else:
                for i in range(self.usageMinimun, self.usageMaximun + 1):
                    self.usage.append(HidUtils.get_usage_name(self.usagePage, i))
        self.signed = self.logicalMinimun < 0
        if self.signed:
            self.__m = 2**self.reportSize - 1
            self.__s = 2 ** (self.reportSize - 1)
        if not (
            self.physicalMaximun is None
            or self.physicalMinimun is None
            or (self.physicalMinimun == self.physicalMinimun == 0)
        ):
            self.__resolution = (self.logicalMaximun - self.logicalMinimun) / (
                (self.physicalMaximun - self.physicalMinimun) * 10**self.unitExponent
            )
        self.byteMap = self.__get_field_map()

    @property
    def bitSize(self):
        return self.reportSize * self.reportCount

    def __get_field_map(self):
        hstart = self.dataIndex
        map = {}
        size = self.reportSize
        assert size > 0
        mask = 2**size - 1
        # Only maps valid usages, anonymous are discarded
        for i in range(len(self.usage)):
            usage = self.usage[i]
            start = hstart + i * size  # bit start in the bit field
            end = start + size - 1  # bit end in the bit field
            bstart = int(start / 8)
            bend = int(end / 8)
            shift = start % 8
            #       usage   index     size           mask            shift
            field = (usage, bstart, bend - bstart + 1, mask << shift, shift)
            for byte in range(field[1], field[1] + field[2]):
                if not byte in map:
                    map[byte] = []
                map[byte].append(field)
        return map

